-- Entitas inti: siswa, program_kursus, tagihan, pembayaran.
-- siswa (1) -------- (N) tagihan (N) -------- (1) program_kursus
--                         |
--                        (1)
--                         |
--                        (N) pembayaran
-- Piutang dihitung sebagai jumlah_tagihan dikurangi SUM(pembayaran.jumlah_bayar).
-- Jalankan di SQL Editor Supabase. Data pada empat tabel inti tetap dipertahankan.

